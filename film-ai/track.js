/* 视频画面中的主体锚点（1920×1080 设计坐标，时间 = 正片秒）。逐帧量自 film.mp4 网格截图，线性插值。 */
window.PV = (function () {
  'use strict';
  const clamp = (x, a = 0, b = 1) => Math.min(b, Math.max(a, x));
  const lin = (t, a, b) => clamp((t - a) / (b - a));
  const mix = (a, b, k) => a + (b - a) * k;
  const eOut = (x) => 1 - Math.pow(1 - x, 3);
  const eIO = (x) => (x < 0.5 ? 4 * x * x * x : 1 - Math.pow(-2 * x + 2, 3) / 2);
  const win = (t, a, b, fi = 0.5, fo = 0.5) => Math.min(lin(t, a, a + fi), 1 - lin(t, b - fo, b));
  function kf(K, t) {
    if (t <= K[0][0]) return K[0].slice(1);
    for (let i = 1; i < K.length; i++) {
      if (t <= K[i][0]) {
        const a = K[i - 1], b = K[i], k = (t - a[0]) / (b[0] - a[0]);
        return a.slice(1).map((v, j) => v + (b[j + 1] - v) * k);
      }
    }
    return K[K.length - 1].slice(1);
  }
  const A = {
    // C1 鹿：两眼之间 + 头部半宽；右侧鹿茸主干中段
    face: [[7.5, 990, 420, 250], [9.3, 945, 420, 240], [11.0, 960, 480, 325], [12.6, 930, 510, 360], [12.84, 925, 515, 365]],
    crown: [[7.5, 1140, 180], [9.3, 1110, 180], [11.0, 1230, 150], [12.6, 1260, 120], [12.84, 1265, 115]],
    // C2 茸根（左右角基）
    burrL: [[12.84, 810, 480], [14.6, 795, 495], [17.07, 825, 465]],
    burrR: [[12.84, 1350, 495], [14.6, 1380, 525], [17.07, 1350, 495]],
    // C3 茸尖
    tip: [[17.07, 965, 230], [17.4, 960, 220], [18.5, 945, 205], [19.6, 945, 145], [21.34, 945, 60]],
    // C4 平放鹿茸：茸根 → 茸尖四个分层点
    bone: [[21.34, 470, 612], [23.45, 300, 660], [25.58, 60, 750], [27.71, 10, 790]],
    blood: [[21.34, 800, 650], [23.45, 760, 672], [25.58, 330, 730], [27.71, 150, 770]],
    powder: [[21.34, 1150, 600], [23.45, 1120, 610], [25.58, 900, 620], [27.71, 780, 711]],
    waxTip: [[21.34, 1440, 490], [23.45, 1450, 490], [25.58, 1440, 500], [27.71, 1470, 470]],
    // C5/C6 蜡片切面：中心 + 半径
    slice: [[27.71, 1175, 535, 380], [28.5, 1179, 534, 393], [31.0, 1200, 534, 465], [33.0, 1224, 540, 532], [34.09, 1235, 540, 560],
      [34.1, 1185, 525, 445], [34.8, 1185, 525, 457], [36.2, 1185, 525, 470]]
  };
  return { clamp, lin, mix, eOut, eIO, win, kf, A };
})();
